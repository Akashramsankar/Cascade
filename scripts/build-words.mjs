// Builds js/words.js from the raw word lists in data/.
//   data/enable1.txt — ENABLE word list (public domain): every word a player may spell.
//   data/common.txt  — ~10k common English words (no swears): the only words that can
//                      form on their own as an Automatic Cascade.
// Usage: node scripts/build-words.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => readFileSync(join(root, 'data', f), 'utf8').split(/\s+/).filter(Boolean);

const MIN = 3;
const MAX = 10; // 25 letter tiles; longer words are vanishingly rare on a 5×6 grid

const valid = read('enable1.txt')
  .map((w) => w.toUpperCase())
  .filter((w) => /^[A-Z]+$/.test(w) && w.length >= MIN && w.length <= MAX);
const validSet = new Set(valid);
const common = [...new Set(read('common.txt').map((w) => w.toUpperCase()))]
  .filter((w) => w.length >= MIN && validSet.has(w));

const out =
  '// Generated by scripts/build-words.mjs — do not edit by hand.\n' +
  `self.CASCADE_WORDS = "${valid.join(' ')}";\n` +
  `self.CASCADE_COMMON = "${common.join(' ')}";\n`;
writeFileSync(join(root, 'js', 'words.js'), out);
console.log(`words.js: ${valid.length} valid words, ${common.length} cascade words, ${(out.length / 1024).toFixed(0)} KB`);
